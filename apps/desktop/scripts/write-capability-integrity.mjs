import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const desktopRoot = path.resolve(here, '..');
const repositoryRoot = path.resolve(desktopRoot, '..', '..');
const defaultSourcePath = path.join(repositoryRoot, 'packages', 'capabilities', 'src', 'windows-capability-bridge.ps1');
const defaultStageDirectory = path.join(desktopRoot, 'build', 'capability-bridge');
const defaultGeneratedOutput = path.join(repositoryRoot, 'packages', 'capabilities', 'src', 'windows-capability-integrity.generated.ts');
const bridgeFileName = 'windows-capability-bridge.ps1';

function sha256(bytes) {
  return createHash('sha256').update(bytes).digest('hex');
}

export async function writeCapabilityIntegrity({
  sourcePath = defaultSourcePath,
  stageDirectory = defaultStageDirectory,
  generatedOutput = defaultGeneratedOutput,
} = {}) {
  const bytes = await readFile(sourcePath);
  const identity = {
    fileName: bridgeFileName,
    sizeBytes: bytes.byteLength,
    sha256: sha256(bytes),
  };

  await mkdir(stageDirectory, { recursive: true });
  await mkdir(path.dirname(generatedOutput), { recursive: true });
  await writeFile(path.join(stageDirectory, bridgeFileName), bytes);
  await writeFile(path.join(stageDirectory, 'windows-capability-bridge.sha256'), `${identity.sha256}  ${bridgeFileName}\n`, 'utf8');
  await writeFile(path.join(stageDirectory, 'windows-capability-bridge.integrity.json'), `${JSON.stringify({ schemaVersion: 1, ...identity }, null, 2)}\n`, 'utf8');
  await writeFile(
    generatedOutput,
    `// Generated by apps/desktop/scripts/write-capability-integrity.mjs.\nexport const WINDOWS_CAPABILITY_BRIDGE_SHA256 = '${identity.sha256}' as const;\nexport const WINDOWS_CAPABILITY_BRIDGE_SIZE_BYTES = ${identity.sizeBytes} as const;\n`,
    'utf8',
  );
  return identity;
}

const invokedPath = process.argv[1] === undefined ? undefined : path.resolve(process.argv[1]);
if (invokedPath === fileURLToPath(import.meta.url)) {
  const identity = await writeCapabilityIntegrity();
  process.stdout.write(`windows-capability-bridge sha256 ${identity.sha256} bytes ${identity.sizeBytes}\n`);
}
